const renderContract = async ({ title, performer = 'Исполнитель', sections }) => {
  const contractSections = [
    ...sections,
    [
      'Цена и порядок оплаты',
      'Общая цена по договору составляет {ДОГОВОРНАЯ_СУММА}.',
      '{ПОРЯДОК_ОПЛАТЫ}',
      'Предварительная оплата, если стороны её согласовали, включается в общую цену договора. Затраты, не включённые в цену, оплачиваются при предварительном согласовании и в соответствии с законом.',
    ],
    ['Изменение и прекращение договора', ...agreedChanges],
    [
      'Общие условия',
      'Договор вступает в силу с момента подписания. Стороны фиксируют изменения и относящиеся к договору уведомления в форме, позволяющей подтвердить их содержание и отправителя.',
      'Ответственность сторон и порядок разрешения споров определяются договором и применимым законодательством Российской Федерации.',
      consumerRights,
    ],
    ['Реквизиты и подписи', '{РЕКВИЗИТЫ_СТОРОН}', '{ПОДПИСИ_СТОРОН}'],
  ]

  return Packer.toBuffer(new Document({
    title,
    styles: {
      default: {
        document: {
          run: { font: 'Times New Roman', size: 22, color: '000000' },
          paragraph: { spacing: { after: 100, line: 276 } },
        },
        title: {
          run: { size: 32, bold: true, color: '000000' },
          paragraph: { spacing: { after: 140 }, keepNext: true },
        },
        heading1: {
          run: { size: 24, bold: true, color: '000000' },
          paragraph: { spacing: { before: 180, after: 75 }, keepNext: true },
        },
      },
    },
    sections: [{
      properties: {
        page: {
          size: { width: 11906, height: 16838 },
          margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 },
        },
      },
      children: [
        new Paragraph({ text: title, heading: HeadingLevel.TITLE }),
        new Paragraph({ text: '№ {НОМЕР_ДОКУМЕНТА}', keepNext: true }),
        new Paragraph({ text: '{ОСНОВНОЙ_ГОРОД}, {ДАТА_ДОГОВОРА}', alignment: AlignmentType.RIGHT, keepNext: true }),
        new Paragraph(`Заказчик — {НАИМЕНОВАНИЕ_КЛИЕНТА}. ${performer} — {ИСПОЛНИТЕЛЬ_ПОДПИСАНТ}. Стороны заключили настоящий договор на следующих условиях.`),
        ...contractSections.flatMap(([heading, ...paragraphs], index) => [
          new Paragraph({ text: `${index + 1} ${heading}`, heading: HeadingLevel.HEADING_1 }),
          ...paragraphs.map((text) => new Paragraph(text)),
        ]),
      ],
    }],
  }))
}

export const getBuiltInContractTemplate = async (id) => {
  const metadata = getBuiltInContractTemplateMetadata(id)
  if (!metadata) return null

  const content = await renderContract(templates[id])
  return { ...metadata, contentBase64: content.toString('base64') }
}
