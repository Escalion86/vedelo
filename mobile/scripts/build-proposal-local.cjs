// Freeze the actual web renderer/sanitizer as local, credential-free runtime strings.
const path = require('node:path'),
  fs = require('node:fs/promises')
const root = path.resolve(__dirname, '../..'),
  feature = path.join(root, 'mobile/src/features/proposals')
const esbuild = require('../node_modules/esbuild'),
  postcss = require('../../node_modules/postcss'),
  tailwind = require('@tailwindcss/postcss')
async function main() {
  const aliases = {
    '@helpers': path.join(root, 'helpers'),
    '@components': path.join(root, 'components'),
    'isomorphic-dompurify': require.resolve('dompurify'),
    react: path.join(root, 'mobile/node_modules/react'),
    'react-dom/client': require.resolve('../node_modules/react-dom/client'),
  }
  const imagePlugin = {
    name: 'local-image',
    setup(build) {
      build.onResolve({ filter: /^next\/image$/ }, () => ({
        path: 'image',
        namespace: 'local',
      }))
      build.onLoad({ filter: /.*/, namespace: 'local' }, () => ({
        contents:
          'import React from "react"; export default function Image({loader,unoptimized,...props}){return React.createElement("img",props)}',
        loader: 'jsx',
        resolveDir: path.join(root, 'mobile'),
      }))
    },
  }
  const output = {}
  for (const mode of ['editor', 'preview']) {
    const result = await esbuild.build({
      entryPoints: [
        `${feature}/runtime/${mode}.${mode === 'preview' ? 'jsx' : 'js'}`,
      ],
      bundle: true,
      write: false,
      outdir: '/tmp/proposal-local',
      format: 'iife',
      platform: 'browser',
      minify: true,
      jsx: 'automatic',
      alias: aliases,
      loader: { '.js': 'jsx' },
      plugins: [imagePlugin],
      define: { 'process.env.NODE_ENV': '"production"' },
    })
    output[mode + 'Js'] = result.outputFiles.find((f) =>
      f.path.endsWith('.js')
    ).text
    output[mode + 'Css'] =
      result.outputFiles.find((f) => f.path.endsWith('.css'))?.text || ''
  }
  const css = `@import "tailwindcss" source(none);\n@source "${root}/components/ProposalPageView.js";\n@source "${root}/components/ProposalRichTextView.js";\n@theme { --breakpoint-tablet: 48rem; }`
  output.utilitiesCss = (
    await postcss([tailwind({ base: root })]).process(css, {
      from: root + '/app/proposal-local.css',
    })
  ).css
  // Reuse the existing rich-text CSS declarations rather than a second style model.
  const globals = await fs.readFile(root + '/app/globals.css', 'utf8')
  const start = globals.indexOf('  .proposal-rich-text-content > * + *')
  const end = globals.indexOf('  .news-rich-text-content', start)
  output.richTextCss = globals.slice(start, end)
  output.fontCss = (
    await Promise.all(
      ['Regular', 'Medium', 'SemiBold', 'Bold'].map(
        async (name, index) =>
          `@font-face{font-family:'Inter Tight';font-weight:${[400, 500, 600, 700][index]};font-display:swap;src:url(data:font/woff2;base64,${(await fs.readFile(root + '/public/fonts/InterTight-' + name + '.woff2')).toString('base64')}) format('woff2')}`
      )
    )
  ).join('')
  output.uploadHelper = await fs.readFile(
    root + '/helpers/escalionCloudUpload.mjs',
    'utf8'
  )
  await fs.writeFile(
    feature + '/localAssets.generated.ts',
    '// Generated by mobile/scripts/build-proposal-local.cjs; source: actual web components/helpers.\n' +
      Object.entries(output)
        .filter(([key]) => key !== 'uploadHelper')
        .map(
          ([key, value]) => `export const ${key} = ${JSON.stringify(value)}\n`
        )
        .join('')
  )
  await fs.writeFile(
    feature + '/uploadUrl.generated.ts',
    '// @ts-nocheck\n// Generated verbatim from helpers/escalionCloudUpload.mjs.\n' +
      output.uploadHelper
  )
  console.log(
    'Built local editor, actual ProposalPageView, sanitizer, CSS and original upload resolver'
  )
}
main().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
