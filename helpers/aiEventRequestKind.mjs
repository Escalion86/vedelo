export function explicitAiEventRequestKind(text) {
  const request = text.trim().toLowerCase()
  if (/^(?:пожалуйста[, ]+)?(?:сколько|когда|где|как|како[йея]|какие|что|почему|кто|есть ли|можно ли|подскажи|покажи|расскажи)(?:\s|[?!,.])/u.test(request)) return 'question'
  const create = /(?:^|[\s,.;])(?:создай|оформи|заведи|добавь|запиши|создать)\s+(?:(?:новую|новый|новое)\s+)?(?:заявк[ау]|заказ|мероприятие|событие)(?=$|[\s,.!?])/u.test(request)
  const edit = /(?:^|[\s,.;])(?:перенеси|измени|исправь|обнови|отредактируй|отмени|закрой|перенести|изменить)(?=$|[\s,.!?])|^(?:добавь|запиши|внеси|создай)\s+(?:оплату|задаток|расход|задачу|контакт|заметку)(?=$|[\s,.!?])/u.test(request)
  if (create && edit) return 'clarify'
  if (create) return 'create'
  if (edit) return 'edit'
  return null
}
