// Подсказка к строке. Для ИИ текст дополняется условиями оплаты этого тарифа.
// Без тарифа (общая строка таблицы) ИИ-подсказка говорит об оплате в общем виде.
export const getTariffFeatureHelp = (key, tariff) => {
  const base = TARIFF_FEATURE_HELP[key]
  if (!base) return ''
  if (key !== 'allowAi') return base

  if (!tariff) {
    return `${base} Сумма, включённая в тариф, тратится в первую очередь, дальше расходы идут с баланса.`
  }

  const includedRub = getAiIncludedRubPerMonth(tariff)
  if (!includedRub) {
    return `${base} В этом тарифе ИИ не включён: запросы оплачиваются с баланса.`
  }
  return `${base} В этом тарифе на ИИ включено ${formatAiIncludedRubles(includedRub)} в месяц: эта сумма тратится в первую очередь, дальше расходы идут с баланса.`
}

// Короткая подпись строки ИИ: «ИИ-возможности (300 ₽ включено)».
export const formatAiIncludedRowLabel = (tariff, base = 'ИИ-возможности') => {
  const includedRub = getAiIncludedRubPerMonth(tariff)
  if (!includedRub) return base
  return `${base} (${formatAiIncludedRubles(includedRub)} включено)`
}

// Короткая подпись для ячейки таблицы: «300 ₽ включено» или пустая строка.
export const formatAiIncludedShort = (tariff) => {
  const includedRub = getAiIncludedRubPerMonth(tariff)
  if (!includedRub) return ''
  return `${formatAiIncludedRubles(includedRub)} включено`
}

